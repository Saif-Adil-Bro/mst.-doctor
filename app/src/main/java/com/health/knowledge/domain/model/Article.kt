package com.health.knowledge.domain.model

import com.health.knowledge.data.local.entity.ArticleEntity

data class Article(
    val id: Int,
    val messageId: String,
    val title: String,
    val content: String,
    val date: String,
    val reactions: Int,
    val medicines: List<String>,
    val categories: List<String>,
    val hasPhoto: Boolean,
    val photoPath: String,
    val syncedFromFirebase: Boolean,
    val firebaseDocId: String,
    val isBookmarked: Boolean,
    val isPinned: Boolean,
    val isReacted: Boolean,
    val isReviewed: Boolean,
    val postKey: String,
    val createdAt: Long = 0L,
    val lastReadAt: Long = 0L,
    val userNote: String = "",
    val isDraft: Boolean = false,
    val isMine: Boolean = false,
    val authorDeviceId: String = "",
    val source: String = "",
    val verifiedCount: Int = 0,
    val isVerified: Boolean = false
)

fun ArticleEntity.toDomain() = Article(
    id = id,
    messageId = messageId,
    title = title,
    content = content,
    date = date,
    reactions = reactions,
    medicines = medicines.split(",").map { it.trim() }.filter { it.isNotBlank() },
    categories = categories.split(",").map { it.trim() }.filter { it.isNotBlank() },
    hasPhoto = hasPhoto,
    photoPath = photoPath,
    syncedFromFirebase = syncedFromFirebase,
    firebaseDocId = firebaseDocId,
    isBookmarked = isBookmarked,
    isPinned = isPinned,
    isReacted = isReacted,
    isReviewed = isReviewed,
    postKey = postKey,
    createdAt = createdAt,
    lastReadAt = lastReadAt,
    userNote = userNote,
    isDraft = isDraft,
    isMine = isMine,
    authorDeviceId = authorDeviceId,
    source = source,
    verifiedCount = verifiedCount,
    isVerified = isVerified
)
